test('参考音按第6至1弦跳过不弹，共用430Hz基准输出精确频率', async ({ page }) => {
  await page.addInitScript(() => {
    const state = { voices: [] as { frequency: number; start: number; stopped: boolean }[] }
    Object.assign(window, { referenceEvidence: state })
    const create = AudioContext.prototype.createOscillator
    AudioContext.prototype.createOscillator = function () {
      const oscillator = create.call(this)
      const evidence = { frequency: 0, start: 0, stopped: false }; state.voices.push(evidence)
      const start = oscillator.start.bind(oscillator); const stop = oscillator.stop.bind(oscillator)
      oscillator.start = (when = 0) => { evidence.frequency = oscillator.frequency.value; evidence.start = when; start(when) }
      oscillator.stop = (when = 0) => { if (when <= this.currentTime) evidence.stopped = true; stop(when) }
      return oscillator
    }
  })
  await page.goto('/')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByLabel('基准音 A4', { exact: true }).fill('430')
  await page.getByRole('button', { name: '和弦', exact: true }).click()
  await page.getByRole('button', { name: 'Am', exact: true }).click()
  await page.getByRole('button', { name: '播放和弦', exact: true }).click()
  type Evidence = { voices: { frequency: number; start: number; stopped: boolean }[] }
  const voices = await page.evaluate(() => (window as unknown as { referenceEvidence: Evidence }).referenceEvidence.voices)
  expect(voices).toHaveLength(5)
  // Independent worked targets: A2, E3, A3, C4, E4 at A4=430 Hz.
  for (const [index, expected] of [107.5, 161.0680108, 215, 255.6795297, 322.1360215].entries()) expect(voices[index].frequency).toBeCloseTo(expected, 2)
  expect(voices[1].start - voices[0].start).toBeCloseTo(.055, 3)
  await page.getByRole('button', { name: '第 5 弦 · 空弦 · A2', exact: true }).click()
  const single = await page.evaluate(() => (window as unknown as { referenceEvidence: Evidence }).referenceEvidence.voices)
  expect(single).toHaveLength(6)
  expect(single[5].frequency).toBeCloseTo(107.5, 3)
  expect(single.slice(0, 5).every(voice => voice.stopped)).toBe(true)
})
