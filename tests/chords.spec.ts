test('和弦文件整份校验、同名新身份、导出往返和写入故障重试', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '和弦', exact: true }).click()
  await page.getByText('和弦文件备份与导入', { exact: true }).click()
  const upload = (chords: unknown[]) => page.getByLabel('导入和弦 JSON', { exact: true }).setInputFiles({ name: 'chords.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ type: 'guitar-learn-chords', version: 1, chords })) })
  const barre = { id: 'builtin-C', name: 'C', frets: [1, 3, 3, 2, 1, 1], fingers: [1, 3, 4, 2, 1, 1], barres: [{ fret: 1, fromString: 6, toString: 1, finger: 1 }] }
  await upload([barre, { name: '坏和弦', frets: [null, null, null, null, null, null] }])
  await expect(page.getByRole('alert')).toContainText('和弦 2')
  await expect(page.getByRole('button', { name: 'C（导入）', exact: true })).toHaveCount(0)
  await upload([barre, barre])
  await expect(page.getByRole('button', { name: 'C（导入 2）', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'C（导入）', exact: true }).click()
  await expect(page.getByLabel('C（导入） 指法图')).toContainText('1')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出全部自定义和弦', exact: true }).click()
  const download = await downloadPromise
  const stream = await download.createReadStream()
  const chunks = []; for await (const chunk of stream!) chunks.push(chunk)
  const file = JSON.parse(Buffer.concat(chunks).toString())
  expect(file.chords).toHaveLength(2)
  expect(file.chords[0].id).not.toBe('builtin-C')
  expect(file.chords[0].barres).toEqual(barre.barres)
  await page.evaluate(() => { const original = Storage.prototype.setItem; Storage.prototype.setItem = function () { throw new Error('满了') }; (window as unknown as { restoreStorage: () => void }).restoreStorage = () => { Storage.prototype.setItem = original } })
  await upload(file.chords)
  await expect(page.getByRole('alert')).toContainText('原库及待导入内容已保留')
  await expect(page.getByRole('button', { name: 'C（导入）（导入）', exact: true })).toHaveCount(0)
  await page.evaluate(() => (window as unknown as { restoreStorage: () => void }).restoreStorage())
  await page.getByRole('button', { name: '重试导入和弦', exact: true }).click()
  await expect(page.getByRole('button', { name: 'C（导入）（导入）', exact: true })).toBeVisible()
})

