import { registerHooks } from 'node:module'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// Resolve the existing extensionless TS data imports without shipping a framework.
registerHooks({ resolve(specifier, context, next) {
  if (specifier.startsWith('.') && context.parentURL) {
    const url = new URL(`${specifier}.ts`, context.parentURL)
    if (existsSync(fileURLToPath(url))) return next(url.href, context)
  }
  return next(specifier, context)
} })
const { lessons } = await import('../src/lessons.ts')
const { exercises } = await import('../src/exercises.ts')
const { gradedRepertoire: scores } = await import('../src/graded-repertoire.ts')
const { repertoireLevels: levels } = await import('../src/repertoire-types.ts')
const { builtinChords: chords } = await import('../src/chords.ts')
const { guitarParts: parts } = await import('../src/guitar-parts.ts')
const content = '// Generated by pnpm wechat:data from shared Web content. Do not edit.\nmodule.exports = ' + JSON.stringify({ lessons, exercises, scores, levels, chords, parts }) + '\n'
const path = new URL('../wechat/miniprogram/data/content.js', import.meta.url)
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== content) throw new Error('WeChat content is stale; run pnpm wechat:data')
} else writeFileSync(path, content)
console.log(`WeChat content ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${lessons.length} lessons, ${Object.keys(exercises).length} exercises, ${scores.length} scores, ${chords.length} chords, ${parts.length} guitar parts.`)
