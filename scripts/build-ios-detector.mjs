import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire, stripTypeScriptTypes } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const packageRoot = dirname(require.resolve('@kretoffer/guitar-audio-kit/package.json'))
const pkg = JSON.parse(readFileSync(resolve(packageRoot, 'package.json'), 'utf8'))
if (pkg.version !== '0.0.2') throw new Error('Revalidate iOS audio before changing guitar-audio-kit@0.0.2')
const source = readFileSync(resolve(packageRoot, 'src/PitchDetector.ts'), 'utf8')
const hash = createHash('sha256').update(source).digest('hex')
const detector = stripTypeScriptTypes(source.replace('export class PitchDetector', 'class PitchDetector'))
const adapter = readFileSync(resolve(root, 'ios/GuitarLearn/Audio/detector-adapter.js'), 'utf8')
const files = {
  'PitchDetector.js': `// Generated by npm run ios:bundle. Do not edit.\n// @kretoffer/guitar-audio-kit@${pkg.version}, MIT.\n// Source SHA-256: ${hash}\n${detector}\n${adapter}`,
  'GuitarAudioKit-LICENSE.txt': readFileSync(resolve(packageRoot, 'LICENSE'), 'utf8'),
}
for (const [name, content] of Object.entries(files)) {
  const path = resolve(root, 'ios/GuitarLearn/Resources', name)
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`${name} is stale; run npm run ios:bundle`)
  } else writeFileSync(path, content)
}
console.log(process.argv.includes('--check') ? 'iOS detector resources match the installed library.' : 'Bundled the unchanged pitch detector and MIT license for JavaScriptCore.')
