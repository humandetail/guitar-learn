import { readdirSync, readFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

// Optional independent syntax pass. Use the WeChat compiler bundled with the
// developer tools, or wechat-miniprogram's miniprogram-compiler package.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../wechat/miniprogram')
const directory = process.env.WECHAT_COMPILER_DIR
if (!directory || !existsSync(resolve(directory, 'wcc')) || !existsSync(resolve(directory, 'wcsc'))) {
  console.error('Set WECHAT_COMPILER_DIR to a directory containing executable wcc and wcsc. This check is not a substitute for WeChat DevTools and device preview.')
  process.exit(1)
}
const all = readdirSync(root, { recursive: true })
const templates = all.filter(file => file.endsWith('.wxml'))
const components = []
let count = 0
for (const file of templates) {
  const config = JSON.parse(readFileSync(resolve(root, file.replace('.wxml', '.json')), 'utf8'))
  if (config.usingComponents) {
    components.push(file, Object.keys(config.usingComponents).length, ...Object.keys(config.usingComponents)); count++
  }
}
components.unshift(count)
const styles = all.filter(file => file.endsWith('.wxss') && file !== 'app.wxss')
for (const [tool, args] of [
  ['wcc', ['-d', '-cc', components.join(' '), ...templates, '-gn', '$gwx']],
  ['wcsc', ['-db', '-pc', String(styles.length), ...styles, 'app.wxss']],
]) {
  const result = spawnSync(resolve(directory, tool), args, { cwd: root, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 })
  if (result.error || result.status !== 0) throw result.error || new Error(`${tool}: ${result.stderr}`)
  if (result.stderr) console.error(result.stderr)
  console.log(`${tool}: passed (${Buffer.byteLength(result.stdout)} generated bytes; not a simulator/device run).`)
}
